-- The current instructor UI expects three Week 1 lessons.
insert into public.week_lessons (week_id, lesson_number, title, description)
select w.id, x.lesson_number, x.title, x.description
from public.learning_weeks w
cross join (values
  (1, 'Literal Computers and the Five Computer Parts', 'CPU, RAM, storage, input, and output.'),
  (2, 'Loading and Classification', 'How programs load and how hardware and software are classified.'),
  (3, 'Language Ladder and Translators', 'How source code reaches the CPU through translators.')
) as x(lesson_number, title, description)
where w.week_number = 1
on conflict (week_id, lesson_number) do update
set title = excluded.title,
    description = excluded.description,
    updated_at = now();

