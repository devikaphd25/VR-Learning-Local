-- Weekly learning content for the VR classroom.
-- Run after 00-base-schema.sql, room-code-migration.sql, and app-data-migration.sql.
-- This migration is additive and safe to rerun.

create table if not exists public.learning_weeks (
    id bigint generated by default as identity primary key,
    week_number integer not null unique check (week_number > 0),
    title text not null,
    description text not null default '',
    is_published boolean not null default false,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.week_lessons (
    id bigint generated by default as identity primary key,
    week_id bigint not null references public.learning_weeks(id) on delete cascade,
    lesson_number integer not null check (lesson_number > 0),
    title text not null,
    description text not null default '',
    is_enabled boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (week_id, lesson_number)
);

create table if not exists public.week_activities (
    id bigint generated by default as identity primary key,
    week_id bigint not null references public.learning_weeks(id) on delete cascade,
    lesson_id bigint references public.week_lessons(id) on delete cascade,
    activity_order integer not null check (activity_order > 0),
    activity_type text not null check (activity_type in ('presentation', 'challenge', 'game', 'briefing')),
    title text not null,
    description text not null default '',
    game_key text,
    asset_path text,
    environment_path text,
    duration_seconds integer check (duration_seconds is null or duration_seconds > 0),
    settings jsonb not null default '{}'::jsonb,
    is_enabled boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

-- Upgrade databases created by the earlier migration version.
alter table public.week_activities
add column if not exists lesson_id bigint references public.week_lessons(id) on delete cascade;

-- Replace the old week-wide ordering constraint with lesson-aware uniqueness.
alter table public.week_activities drop constraint if exists week_activities_week_id_activity_order_key;
create unique index if not exists week_activities_lesson_order_idx
on public.week_activities(lesson_id, activity_order)
where lesson_id is not null;
create unique index if not exists week_activities_week_game_order_idx
on public.week_activities(week_id, activity_order)
where lesson_id is null;
create index if not exists week_lessons_week_id_idx on public.week_lessons(week_id, lesson_number);
create index if not exists week_activities_week_id_idx on public.week_activities(week_id, activity_order);
create index if not exists week_activities_lesson_id_idx on public.week_activities(lesson_id, activity_order);

alter table public.quiz_questions
add column if not exists activity_id bigint references public.week_activities(id) on delete set null;
create index if not exists quiz_questions_activity_id_idx on public.quiz_questions(activity_id);

alter table public.game_results
add column if not exists activity_id bigint references public.week_activities(id) on delete set null;
create index if not exists game_results_activity_id_idx on public.game_results(activity_id);

alter table public.rooms
add column if not exists active_week_id bigint references public.learning_weeks(id) on delete set null;
create index if not exists rooms_active_week_id_idx on public.rooms(active_week_id);

alter table public.learning_weeks enable row level security;
alter table public.week_lessons enable row level security;
alter table public.week_activities enable row level security;

